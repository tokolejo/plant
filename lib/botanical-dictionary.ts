export function lookupBotanicalTaxon(scientificName: string, commonNames: string[] = []): BotanicalTaxon {
  const s = scientificName.toLowerCase();
  for (const [key, val] of Object.entries(BOTANICAL_TAXONOMY_MAP)) {
    if (s.includes(key)) return val;
  }
  for (const cn of commonNames) {
    const c = cn.toLowerCase();
    for (const [key, val] of Object.entries(BOTANICAL_TAXONOMY_MAP)) {
      if (c.includes(key)) return val;
    }
  }

  // Fallback to structured categories match
  const matched = STRUCTURED_CATEGORIES.find((c) =>
    c.keywords.some((k) => s.includes(k.toLowerCase()))
  );

  return {
    ka: matched ? matched.nameKa.split("(")[0].trim() : scientificName,
    en: matched ? matched.nameEn : scientificName,
    categoryId: matched ? matched.id : "other-plant",
    wateringKa: "კვირაში 1-ხელ (ნიადაგის შეშრობისას)",
    wateringEn: "Weekly when topsoil dries",
    lightKa: "კაშკაშა გაფანტული სინათლე",
    lightEn: "Bright indirect light",
    difficulty: "Easy",
    toxicityKa: "გადაამოწმეთ ინდივიდუალურად",
    toxicityEn: "Check pet toxicity",
    tags: ["მცენარე", "ოთახის მცენარე"],
  };
}
